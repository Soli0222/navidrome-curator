export const languages = [
  { code: 'ja', label: '日本語' },
  { code: 'en', label: 'English' },
];

const fallback = 'ja';
let current = fallback;

try {
  const saved = localStorage.getItem('lang');
  if (saved && messages[saved]) current = saved;
} catch {
  // ストレージが使えなくても既定の言語で動かす。
}

export function lang() {
  return current;
}

export function setLang(code) {
  if (!messages[code]) return;
  current = code;
  try {
    localStorage.setItem('lang', code);
  } catch {
    // 保存できなくても切り替えは続ける。
  }
}

export function t(key, params = {}) {
  const s = messages[current][key] ?? messages[fallback][key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

export function errorText(code, message) {
  const key = `error.${code}`;
  if (messages[current][key] || messages[fallback][key]) return t(key);
  return t('error.generic', { msg: message || code });
}
